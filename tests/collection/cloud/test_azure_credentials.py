class TestHarvestAzureProfile:
    def test_parses_subscriptions(self, tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> None:
        for name in (
            "AZURE_TENANT_ID",
            "AZURE_CLIENT_ID",
            "AZURE_CLIENT_SECRET",
            "AZURE_STORAGE_CONNECTION_STRING",
        ):
            monkeypatch.delenv(name, raising=False)
        azure_dir = tmp_path / ".azure"
        azure_dir.mkdir()
        profile = {
            "subscriptions": [
                {
                    "id": "sub-guid-1",
                    "name": "Prod",
                    "state": "Enabled",
                    "tenantId": "tenant-1",
                    "environmentName": "AzureCloud",
                    "user": {"name": "ops@acme.example", "type": "user"},
                },
                {
                    "id": "sub-guid-2",
                    "name": "Dev",
                    "tenantId": "tenant-2",
                    "user": {"name": "sp:client-guid", "type": "servicePrincipal"},
                },
            ]
        }
        (azure_dir / "azureProfile.json").write_text(json.dumps(profile), encoding="utf-8-sig")

        creds = harvest_azure_credentials(azure_dir=azure_dir, include_imds=False)

        subs = [c for c in creds if c.type == "subscription_context"]
        assert {c.subscription_id for c in subs} == {"sub-guid-1", "sub-guid-2"}
        prod = next(c for c in subs if c.subscription_id == "sub-guid-1")
        assert prod.tenant_id == "tenant-1"
        assert prod.extra.get("name") == "Prod"
        assert prod.extra.get("user_type") == "user"

    def test_malformed_json_ignored(self, tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> None:
        for name in ("AZURE_TENANT_ID", "AZURE_CLIENT_ID", "AZURE_CLIENT_SECRET", "AZURE_STORAGE_CONNECTION_STRING"):
            monkeypatch.delenv(name, raising=False)
        azure_dir = tmp_path / ".azure"
        azure_dir.mkdir()
        (azure_dir / "azureProfile.json").write_text("{not json", encoding="utf-8")

        creds = harvest_azure_credentials(azure_dir=azure_dir, include_imds=False)

        assert creds == []


