class TestHarvestServicePrincipals:
    def test_hashes_client_secret_and_certificate(self, tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> None:
        for name in ("AZURE_TENANT_ID", "AZURE_CLIENT_ID", "AZURE_CLIENT_SECRET", "AZURE_STORAGE_CONNECTION_STRING"):
            monkeypatch.delenv(name, raising=False)
        azure_dir = tmp_path / ".azure"
        azure_dir.mkdir()
        entries = [
            {
                "client": "sp-guid-1",
                "tenant": "tenant-guid-1",
                "clientSecret": "sp-secret-value",
            },
            {
                "clientId": "sp-guid-2",
                "tenantId": "tenant-guid-2",
                "certificate": "AA:BB:CC:DD:EE:FF",
            },
        ]
        (azure_dir / "service_principal_entries.json").write_text(json.dumps(entries), encoding="utf-8")

        creds = harvest_azure_credentials(azure_dir=azure_dir, include_imds=False)

        sps = [c for c in creds if c.type == "service_principal"]
        assert len(sps) == 2
        secret_row = next(c for c in sps if c.client_id == "sp-guid-1")
        assert secret_row.secret_hash == _sha256("sp-secret-value")
        cert_row = next(c for c in sps if c.client_id == "sp-guid-2")
        assert cert_row.extra.get("certificate_thumbprint_hash") == _sha256("AA:BB:CC:DD:EE:FF")
        payload = json.dumps([c.to_dict() for c in sps])
        assert "sp-secret-value" not in payload
        assert "AA:BB:CC:DD:EE:FF" not in payload


