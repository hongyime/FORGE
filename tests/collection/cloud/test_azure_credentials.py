class TestHarvestEnv:
    def test_service_principal_env_hashed(self, monkeypatch: pytest.MonkeyPatch, tmp_path: Path) -> None:
        monkeypatch.setenv("AZURE_TENANT_ID", "tenant-guid")
        monkeypatch.setenv("AZURE_CLIENT_ID", "client-guid")
        monkeypatch.setenv("AZURE_CLIENT_SECRET", "super-secret")
        monkeypatch.delenv("AZURE_STORAGE_CONNECTION_STRING", raising=False)

        creds = harvest_azure_credentials(azure_dir=tmp_path / "empty", include_imds=False)

        sp = [c for c in creds if c.type == "service_principal"]
        assert len(sp) == 1
        row = sp[0]
        assert row.tenant_id == "tenant-guid"
        assert row.client_id == "client-guid"
        assert row.secret_hash == _sha256("super-secret")
        # Raw secret must never leak.
        assert row.secret_hash != "super-secret"
        assert "super-secret" not in json.dumps(row.to_dict())

    def test_storage_connection_string_extracts_account_and_hashes_key(
        self, monkeypatch: pytest.MonkeyPatch, tmp_path: Path
    ) -> None:
        cs = (
            "DefaultEndpointsProtocol=https;"
            "AccountName=acmedata;"
            "AccountKey=SGVsbG9Xb3JsZEtleU1hdGVyaWFsMTIzNDU2Nzg5MEFCQ0RFRkc=;"
            "EndpointSuffix=core.windows.net"
        )
        monkeypatch.setenv("AZURE_STORAGE_CONNECTION_STRING", cs)
        monkeypatch.delenv("AZURE_CLIENT_ID", raising=False)
        monkeypatch.delenv("AZURE_CLIENT_SECRET", raising=False)
        monkeypatch.delenv("AZURE_TENANT_ID", raising=False)

        creds = harvest_azure_credentials(azure_dir=tmp_path / "empty", include_imds=False)

        storage = [c for c in creds if c.type == "storage_shared_key"]
        assert len(storage) == 1
        row = storage[0]
        assert row.account_name == "acmedata"
        assert row.secret_hash == _sha256("SGVsbG9Xb3JsZEtleU1hdGVyaWFsMTIzNDU2Nzg5MEFCQ0RFRkc=")
        assert "SGVsbG9Xb3JsZEtleU1hdGVyaWFsMTIzNDU2Nzg5MEFCQ0RFRkc=" not in json.dumps(row.to_dict())

    def test_missing_env_produces_nothing(self, monkeypatch: pytest.MonkeyPatch, tmp_path: Path) -> None:
        for name in (
            "AZURE_TENANT_ID",
            "AZURE_CLIENT_ID",
            "AZURE_CLIENT_SECRET",
            "AZURE_STORAGE_CONNECTION_STRING",
        ):
            monkeypatch.delenv(name, raising=False)

        creds = harvest_azure_credentials(azure_dir=tmp_path / "empty", include_imds=False)

        assert creds == []


