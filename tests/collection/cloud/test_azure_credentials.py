"""Tests for forge.collection.cloud.azure_credentials.

Every test hashes any secret material and asserts that raw values never appear
in the returned dataclass. The IMDS probe is guarded by a fake urlopen so no
real network traffic is generated by the test suite.
"""

from __future__ import annotations

import hashlib
import json
from pathlib import Path
from unittest.mock import patch

import pytest

from forge.collection.cloud.azure_credentials import (
    AzureCredential,
    _HASH_PREFIX,
    _sha256,
    harvest_azure_credentials,
)


# --------------------------------------------------------------------------- #
# Hash helper                                                                 #
# --------------------------------------------------------------------------- #

class TestSha256:
    def test_hashes_str_with_prefix(self) -> None:
        expected = _HASH_PREFIX + hashlib.sha256(b"secret").hexdigest()
        assert _sha256("secret") == expected

    def test_hashes_bytes_with_prefix(self) -> None:
        expected = _HASH_PREFIX + hashlib.sha256(b"payload").hexdigest()
        assert _sha256(b"payload") == expected

    def test_none_returns_none(self) -> None:
        assert _sha256(None) is None

    def test_empty_returns_none(self) -> None:
        assert _sha256("") is None
        assert _sha256(b"") is None


