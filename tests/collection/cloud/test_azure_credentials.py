class _FakeResponse:
    def __init__(self, body: bytes) -> None:
        self._body = body

    def read(self) -> bytes:
        return self._body

    def __enter__(self) -> "_FakeResponse":
        return self

    def __exit__(self, *exc: object) -> None:  # noqa: D401
        pass


class TestHarvestImds:
    def test_hashes_managed_identity_token(self, tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> None:
        for name in ("AZURE_TENANT_ID", "AZURE_CLIENT_ID", "AZURE_CLIENT_SECRET", "AZURE_STORAGE_CONNECTION_STRING"):
            monkeypatch.delenv(name, raising=False)
        body = json.dumps(
            {
                "access_token": "eyJ0eXAiOi.mi-token",
                "client_id": "mi-client-guid",
                "resource": "https://management.azure.com/",
                "expires_in": "3600",
                "token_type": "Bearer",
            }
        ).encode("utf-8")
        with patch(
            "forge.collection.cloud.azure_credentials.urlrequest.urlopen",
            return_value=_FakeResponse(body),
        ):
            creds = harvest_azure_credentials(azure_dir=tmp_path / "empty", include_imds=True)

        mi = [c for c in creds if c.type == "managed_identity_token"]
        assert len(mi) == 1
        assert mi[0].client_id == "mi-client-guid"
        assert mi[0].access_token_hash == _sha256("eyJ0eXAiOi.mi-token")
        assert mi[0].extra.get("resource") == "https://management.azure.com/"
        assert "eyJ0eXAiOi.mi-token" not in json.dumps(mi[0].to_dict())

    def test_imds_timeout_returns_empty(self, tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> None:
        for name in ("AZURE_TENANT_ID", "AZURE_CLIENT_ID", "AZURE_CLIENT_SECRET", "AZURE_STORAGE_CONNECTION_STRING"):
            monkeypatch.delenv(name, raising=False)

        def _raise(*args: object, **kwargs: object) -> None:
            raise TimeoutError("imds timeout")

        with patch(
            "forge.collection.cloud.azure_credentials.urlrequest.urlopen",
            side_effect=_raise,
        ):
            creds = harvest_azure_credentials(
                azure_dir=tmp_path / "empty", include_imds=True, imds_timeout=0.01
            )

        assert [c for c in creds if c.type == "managed_identity_token"] == []

    def test_include_imds_false_skips_probe(self, tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> None:
        for name in ("AZURE_TENANT_ID", "AZURE_CLIENT_ID", "AZURE_CLIENT_SECRET", "AZURE_STORAGE_CONNECTION_STRING"):
            monkeypatch.delenv(name, raising=False)

        with patch(
            "forge.collection.cloud.azure_credentials.urlrequest.urlopen",
            side_effect=AssertionError("must not probe IMDS when disabled"),
        ):
            creds = harvest_azure_credentials(azure_dir=tmp_path / "empty", include_imds=False)

        assert creds == []


