class TestHarvestMsalCache:
    def test_parses_access_and_refresh_tokens(self, tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> None:
        for name in ("AZURE_TENANT_ID", "AZURE_CLIENT_ID", "AZURE_CLIENT_SECRET", "AZURE_STORAGE_CONNECTION_STRING"):
            monkeypatch.delenv(name, raising=False)
        azure_dir = tmp_path / ".azure"
        azure_dir.mkdir()
        cache = {
            "AccessToken": {
                "u-1": {
                    "client_id": "app-guid",
                    "realm": "tenant-guid",
                    "secret": "eyJraWQ.access-token",
                }
            },
            "RefreshToken": {
                "r-1": {
                    "client_id": "app-guid",
                    "secret": "OAQABAAA.refresh-token",
                }
            },
        }
        (azure_dir / "msal_token_cache.json").write_text(json.dumps(cache), encoding="utf-8")

        creds = harvest_azure_credentials(azure_dir=azure_dir, include_imds=False)

        access = [c for c in creds if c.type == "msal_access_token"]
        refresh = [c for c in creds if c.type == "msal_refresh_token"]
        assert len(access) == 1
        assert len(refresh) == 1
        assert access[0].access_token_hash == _sha256("eyJraWQ.access-token")
        assert refresh[0].refresh_token_hash == _sha256("OAQABAAA.refresh-token")
        payload = json.dumps([c.to_dict() for c in creds])
        assert "eyJraWQ.access-token" not in payload
        assert "OAQABAAA.refresh-token" not in payload

    def test_encrypted_cache_hashes_whole_blob(self, tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> None:
        for name in ("AZURE_TENANT_ID", "AZURE_CLIENT_ID", "AZURE_CLIENT_SECRET", "AZURE_STORAGE_CONNECTION_STRING"):
            monkeypatch.delenv(name, raising=False)
        azure_dir = tmp_path / ".azure"
        azure_dir.mkdir()
        blob = b"\x01\x00DPAPI-encrypted-blob"
        (azure_dir / "msal_token_cache.json").write_bytes(blob)

        creds = harvest_azure_credentials(azure_dir=azure_dir, include_imds=False)

        encrypted = [c for c in creds if c.type == "msal_encrypted_cache"]
        assert len(encrypted) == 1
        assert encrypted[0].access_token_hash == _sha256(blob)
        assert encrypted[0].extra.get("cache_size_bytes") == str(len(blob))


